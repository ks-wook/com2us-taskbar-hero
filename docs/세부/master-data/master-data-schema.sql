-- 11b. stage_spawn — 스테이지별 등장 몬스터·레벨 (stage_master 자식, 값 문서 §11-B)
--    구 stage_master.spawns(JSON 배열)를 대체하는 자식 테이블(JSON 컬럼 미사용 규칙).
--    (stage_id, monster_code) 복합 PK. 보스도 이 테이블에 is_boss=1 행으로 둔다
--    (구 stage_master.boss_monster_code 폐기) — 보스 행은 spawn_count=1 이며 한 스테이지에 최대 1행이다.
--    monster_level: 그 스테이지에서 이 몬스터가 등장하는 레벨(1 이상). 실제 전투 스탯은
--      monster_master 의 레벨 1 기준값(12종 전부 hp 50 · attack 일반 5/보스 1)에 레벨 배율을
--      곱해 클라이언트가 산출한다(값 문서 §9.4).
--      hp = round(base_hp × 1.25^(level-1)) / attack = round(base_attack × 1.18^(level-1)).
--    ★ 난이도는 이 컬럼이 만든다 — 기준값이 역할별로 한 벌뿐이므로, 스테이지가 오를수록 세지는 것은
--      전부 등장 레벨이 오르기 때문이다. 레벨 곡선(값 문서 §11-B):
--        · 지역 안에서 3스테이지마다 +1 — s1~3 / s4~6 / s7~10 세 구간
--        · 지역이 바뀌면 +3~4 (파티가 장비 한 등급을 갈아입는 계단에 맞춘다)
--        · Act1·2는 일반 2종이라 강몹이 약몹보다 +1 레벨이고, 스테이지가 오를수록 약몹이 강몹으로 교체된다
--        · 결과: 1지역 Lv1~4 → 2지역 Lv8~11 → 3지역 Lv15~17 → 4지역 Lv19~21 → 5지역 Lv24~26 (단조 증가)
